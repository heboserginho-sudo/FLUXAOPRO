package com.example.data.i18n

data class CountryConfiguration(
    val countryCode: String,
    val countryName: String,
    val flag: String,
    val phoneCode: String,
    val currency: String,
    val currencySymbol: String,
    val taxIdLabel: String,
    val taxIdType: String,
    val taxIdRequired: Boolean = true,
    val taxAuthority: String,
    val defaultLanguage: String,
    val timezone: String,
    val phoneSample: String = ""
)

data class CountryInfo(
    val isoCode: String,
    val name: String,
    val flag: String,
    val callingCode: String,
    val defaultCurrency: String,
    val defaultLanguage: String,
    val defaultTimezone: String,
    val taxIdLabel: String,
    val postalCodeLabel: String,
    val requiresPostalCode: Boolean = true,
    val phoneSample: String = "",
    val taxAuthority: String = "Autoridade Fiscal",
    val taxIdType: String = "TAX_ID",
    val currencySymbol: String = "$"
) {
    fun toCountryConfiguration(): CountryConfiguration {
        return CountryConfiguration(
            countryCode = isoCode,
            countryName = name,
            flag = flag,
            phoneCode = callingCode,
            currency = defaultCurrency,
            currencySymbol = currencySymbol,
            taxIdLabel = taxIdLabel,
            taxIdType = taxIdType,
            taxIdRequired = true,
            taxAuthority = taxAuthority,
            defaultLanguage = defaultLanguage,
            timezone = defaultTimezone,
            phoneSample = phoneSample
        )
    }
}

